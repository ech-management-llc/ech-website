#!/usr/bin/env node
/**
 * build-listings.js — regenerate ECH listing pages from data/listings.json.
 *
 * The site stays plain static HTML on GitHub Pages (no runtime JS, crawler-safe).
 * This script is the only thing that writes listing cards.
 *
 *   node tools/build-listings.js            # write pages
 *   node tools/build-listings.js --check    # exit 1 if pages are out of date (CI / pre-commit)
 *
 * Photo rule: if a listing has photos[], the first photo becomes the card hero and the rest
 * become thumbnails. With no photos, the inline SVG scene from data/scenes.json is used, so
 * a listing never renders as an empty grey box.
 *
 * Contract: see docs/FL_LISTINGS_CONTRACT.md — listings.json is the seam Foundation Layer
 * takes over later. This renderer does not care where the JSON came from.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DATA = path.join(ROOT, 'data');

const PAGES = {
  'single-family': 'single-family-home-rental-cedar-creek-lake.html',
  apartment: 'apartment-rental-cedar-creek-lake.html',
};

const START = '<!-- LISTINGS:START (generated by tools/build-listings.js — edit data/listings.json, not this) -->';
const END = '<!-- LISTINGS:END -->';

const APPLY_URL = 'https://app.rentredi.com/apply';

const NOTE_CLASS = {
  available: 'avail-note',
  coming_soon: 'soon-note',
  leased: 'leased-note',
  inquire: 'inquire-note',
};

const BADGE_CLASS = {
  available: 'status-avail',
  coming_soon: 'status-soon',
  leased: 'status-rented',
  inquire: 'status-inquire',
};

const DEFAULT_BADGE = {
  available: 'Available',
  coming_soon: 'Coming Soon',
  leased: 'Rented',
  inquire: 'Inquire',
};

// ---------------------------------------------------------------- helpers

const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const escAttr = (s) => esc(s).replace(/"/g, '&quot;');

// single quotes inside an inline onclick="openWaitlist('...')"
const escJsAttr = (s) => escAttr(s).replace(/'/g, '&#39;');

const commas = (n) => Number(n).toLocaleString('en-US');

const money = (n) => `$${commas(n)}/mo`;

/** "2" not "2.0"; "1.5" stays "1.5" */
const numStr = (n) => (Number.isInteger(Number(n)) ? String(Number(n)) : String(n));

function fail(msg) {
  console.error(`✗ ${msg}`);
  process.exitCode = 1;
}

// ---------------------------------------------------------------- validation

const REQUIRED = ['id', 'page', 'address', 'city', 'status', 'kind'];

function validate(listings, scenes) {
  const errors = [];
  const seen = new Set();

  listings.forEach((l, i) => {
    const where = `listings[${i}] (${l.id || 'no id'})`;

    REQUIRED.forEach((k) => {
      if (l[k] === undefined || l[k] === null || l[k] === '') {
        errors.push(`${where}: missing required field "${k}"`);
      }
    });

    if (l.id) {
      if (seen.has(l.id)) errors.push(`${where}: duplicate id "${l.id}"`);
      seen.add(l.id);
      if (!/^[a-z0-9-]+$/.test(l.id)) {
        errors.push(`${where}: id must be lowercase letters, numbers and hyphens only`);
      }
    }

    if (l.page && !PAGES[l.page]) {
      errors.push(`${where}: unknown page "${l.page}" (expected: ${Object.keys(PAGES).join(', ')})`);
    }

    if (l.status && !BADGE_CLASS[l.status]) {
      errors.push(
        `${where}: unknown status "${l.status}" (expected: ${Object.keys(BADGE_CLASS).join(', ')})`
      );
    }

    if (l.cta && !['apply', 'waitlist', 'none'].includes(l.cta)) {
      errors.push(`${where}: unknown cta "${l.cta}" (expected: apply, waitlist, none)`);
    }

    if (l.cta === 'waitlist' && !l.waitlist_label) {
      errors.push(`${where}: cta "waitlist" requires waitlist_label`);
    }

    // A photo that isn't actually there would render as a broken image on the public site.
    // Two valid forms: an absolute https URL (Supabase public bucket — the phone path) or a
    // repo-relative path under /assets (the desktop path). Anything else is a typo.
    (l.photos || []).forEach((p) => {
      if (/^https:\/\//.test(p)) return; // remote host; reachability is checked at upload time
      if (/^http:\/\//.test(p)) {
        errors.push(`${where}: photo must be https, not http — ${p}`);
        return;
      }
      if (!p.startsWith('/assets/')) {
        errors.push(`${where}: photo must be an https URL or start with /assets/ — ${p}`);
        return;
      }
      if (!fs.existsSync(path.join(ROOT, p.replace(/^\//, '')))) {
        errors.push(`${where}: photo not found on disk — ${p}`);
      }
    });

    // A listing with no photos falls back to its SVG scene. If that scene name is wrong the card
    // would render as a bare badge on an empty box, so this must fail the build, not degrade.
    if ((l.photos || []).length === 0) {
      if (!l.scene) {
        errors.push(`${where}: has no photos and no scene — the card would render empty`);
      } else if (!scenes[l.scene]) {
        errors.push(`${where}: unknown scene "${l.scene}" (see: listing-edit.js scenes)`);
      }
    }

    if (l.kind === 'multifamily' && (!l.floor_plans || l.floor_plans.length === 0)) {
      errors.push(`${where}: multifamily listing has no floor_plans`);
    }

    if (l.kind !== 'multifamily' && l.rent == null && l.status !== 'leased') {
      errors.push(`${where}: available/coming-soon listing has no rent (would render blank price)`);
    }
  });

  return errors;
}

// ---------------------------------------------------------------- rendering

/** The card image well: photos if we have them, otherwise the SVG scene. */
function renderWell(l, scenes) {
  const badgeClass = BADGE_CLASS[l.status];
  const badgeLabel = esc(l.badge_label || DEFAULT_BADGE[l.status]);
  const badge = `<span class="status-badge ${badgeClass}">${badgeLabel}</span>`;
  const photos = l.photos || [];

  if (photos.length === 0) {
    const scene = scenes[l.scene];
    if (!scene) {
      fail(`listing "${l.id}" references unknown scene "${l.scene}"`);
      return `<div class="photo-ph">${badge}</div>`;
    }
    return `<div class="photo-ph">${scene}${badge}</div>`;
  }

  const alt = escAttr(`${l.address}, ${l.city} ${l.state || 'TX'}`);
  const heroId = `hero-${l.id}`;
  const hero =
    `<img class="listing-img" id="${heroId}" src="${escAttr(photos[0])}" alt="${alt}"` +
    ` loading="lazy" decoding="async">`;

  let out = `<div class="photo-ph has-photo">${hero}${badge}</div>`;

  if (photos.length > 1) {
    const thumbs = photos
      .map((p, i) => {
        const sel = i === 0 ? ' aria-current="true"' : '';
        return (
          `<button type="button" class="thumb" data-src="${escAttr(p)}"${sel}` +
          ` onclick="swapHero('${heroId}',this)" aria-label="Photo ${i + 1} of ${photos.length}">` +
          `<img src="${escAttr(p)}" alt="" loading="lazy" decoding="async"></button>`
        );
      })
      .join('');
    out += `<div class="thumbs">${thumbs}</div>`;
  }

  return out;
}

function renderCta(l, mf) {
  const parts = [];
  if (l.cta === 'apply') {
    const style = mf ? ' style="margin-top:10px;"' : '';
    parts.push(`<a href="${APPLY_URL}" class="btn"${style}>Apply Now</a>`);
  } else if (l.cta === 'waitlist') {
    const style = mf ? ' style="margin-top:6px;"' : '';
    parts.push(
      `<button type="button" class="btn"${style}` +
        ` onclick="openWaitlist('${escJsAttr(l.waitlist_label)}')">Join the Waitlist</button>`
    );
  }
  if (l.virtual_tour) {
    parts.push(
      `<a href="${escAttr(l.virtual_tour)}" class="btn btn-secondary btn-tour">🎥 Virtual Tour</a>`
    );
  }
  return parts.join('');
}

function renderSfr(l, scenes) {
  const leased = l.status === 'leased';
  const h3 = leased
    ? `<h3 class="leased">${esc(l.address)}</h3>`
    : `<h3>${esc(l.address)}</h3>`;

  let body = h3;
  body += `<p class="meta"><span>📍 ${esc(l.city)}, ${esc(l.state || 'TX')}</span></p>`;

  const specs = [];
  if (l.beds != null) specs.push(`<span>🛏️ ${numStr(l.beds)} bed</span>`);
  if (l.baths != null) specs.push(`<span>🛁 ${numStr(l.baths)} bath</span>`);
  if (l.sqft != null) specs.push(`<span>📐 ${commas(l.sqft)} sqft</span>`);
  if (specs.length) body += `<p class="meta">${specs.join('')}</p>`;

  if (l.rent != null) {
    const style = leased ? ' style="opacity:.65;"' : '';
    body += `<p class="price"${style}>${money(l.rent)}</p>`;
  }

  if (l.note) body += `<p class="${NOTE_CLASS[l.status]}">${esc(l.note)}</p>`;

  body += renderCta(l, false);

  return `<article class="listing-card">${renderWell(l, scenes)}<div class="body">${body}</div></article>`;
}

function renderPlan(p) {
  const bits = [];
  if (p.beds != null) bits.push(`${numStr(p.beds)} bd`);
  if (p.baths != null) bits.push(`${numStr(p.baths)} ba`);
  let text = bits.join(' / ');
  if (p.sqft != null) text += `${text ? ' · ' : ''}${commas(p.sqft)} sqft`;

  const leased = p.status === 'leased';

  if (leased) {
    const rent = p.rent != null ? ` · ${money(p.rent)}` : '';
    return `<li class="leased">${text}${rent} <span class="tag-le">· Leased</span></li>`;
  }

  const n = p.available_count == null ? 1 : p.available_count;
  const tag = n > 1 ? `· ${n} available` : '· Available';
  const rent = p.rent != null ? ` · <strong>${money(p.rent)}</strong>` : '';
  return `<li>${text}${rent} <span class="tag-av">${tag}</span></li>`;
}

function renderMf(l, scenes) {
  const leased = l.status === 'leased';
  const h3 = leased
    ? `<h3 style="opacity:.8;">${esc(l.address)}</h3>`
    : `<h3>${esc(l.address)}</h3>`;

  let body = h3;
  body += `<p class="meta"><span>📍 ${esc(l.city)}, ${esc(l.state || 'TX')}</span></p>`;

  // Availability note sits above the floor plans for available buildings, below for leased ones
  // (matches the hand-built pages: a leased building leads with plans, then the waitlist pitch).
  if (l.note && !leased) body += `<p class="${NOTE_CLASS[l.status]}">${esc(l.note)}</p>`;

  const plans = l.floor_plans || [];
  if (plans.length) {
    body += `<p class="fp-label">${plans.length > 1 ? 'Floor plans' : 'Floor plan'}</p>`;
    body += `<ul class="fp">${plans.map(renderPlan).join('')}</ul>`;
  }

  if (l.all_bills_paid) {
    const txt = esc(l.bills_text || 'Electricity, water, sewer, trash & internet included.');
    body += `<div class="bills"><strong>✓ All Bills Paid</strong>${txt}</div>`;
  }

  if (l.note && leased) body += `<p class="${NOTE_CLASS[l.status]}">${esc(l.note)}</p>`;

  body += renderCta(l, true);

  return `<article class="listing-card">${renderWell(l, scenes)}<div class="body">${body}</div></article>`;
}

// ---------------------------------------------------------------- page write

function buildGrid(listings, scenes, page) {
  const rows = listings
    .filter((l) => l.page === page)
    .slice()
    .sort((a, b) => (a.order ?? 999) - (b.order ?? 999));

  return rows
    .map((l) => (l.kind === 'multifamily' ? renderMf(l, scenes) : renderSfr(l, scenes)))
    .join('\n\n');
}

function splice(html, grid, file) {
  const a = html.indexOf(START);
  const b = html.indexOf(END);

  if (a === -1 || b === -1) {
    fail(
      `${file} is missing build markers.\n` +
        `  Wrap the listing cards in:\n    ${START}\n    ...cards...\n    ${END}`
    );
    return null;
  }
  if (b < a) {
    fail(`${file}: LISTINGS:END appears before LISTINGS:START`);
    return null;
  }

  return html.slice(0, a + START.length) + '\n\n' + grid + '\n\n' + html.slice(b);
}

function main() {
  const check = process.argv.includes('--check');

  let data, scenes;
  try {
    data = JSON.parse(fs.readFileSync(path.join(DATA, 'listings.json'), 'utf8'));
    scenes = JSON.parse(fs.readFileSync(path.join(DATA, 'scenes.json'), 'utf8'));
  } catch (e) {
    console.error(`✗ could not read data files: ${e.message}`);
    process.exit(1);
  }

  const listings = data.listings || [];
  const errors = validate(listings, scenes);
  if (errors.length) {
    console.error(`✗ ${errors.length} validation error(s) — nothing written:\n`);
    errors.forEach((e) => console.error(`   ${e}`));
    process.exit(1);
  }

  // Render every page fully BEFORE writing any of them. A failure discovered mid-render must not
  // leave one page updated and the other stale, or a half-good page on the live site.
  const planned = [];
  for (const [page, file] of Object.entries(PAGES)) {
    const full = path.join(ROOT, file);
    const before = fs.readFileSync(full, 'utf8');
    const after = splice(before, buildGrid(listings, scenes, page), file);
    if (after === null) continue;
    planned.push({ page, file, full, before, after });
  }

  if (process.exitCode) {
    console.error('\n✗ rendering failed — nothing written');
    process.exit(1);
  }

  let changed = 0;
  const summary = [];

  for (const { page, file, full, before, after } of planned) {
    const n = listings.filter((l) => l.page === page).length;
    const withPhotos = listings.filter((l) => l.page === page && (l.photos || []).length).length;

    if (after !== before) {
      changed++;
      if (!check) fs.writeFileSync(full, after, 'utf8');
      summary.push(`${check ? 'STALE' : 'wrote'}  ${file}  (${n} listings, ${withPhotos} with photos)`);
    } else {
      summary.push(`ok     ${file}  (${n} listings, ${withPhotos} with photos)`);
    }
  }

  summary.forEach((s) => console.log(s));

  if (check && changed) {
    console.error(`\n✗ ${changed} page(s) out of date — run: node tools/build-listings.js`);
    process.exit(1);
  }
  console.log(
    check
      ? '\n✓ pages match data/listings.json'
      : `\n✓ build complete — ${changed} page(s) updated`
  );
}

main();
